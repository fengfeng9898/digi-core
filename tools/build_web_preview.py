#!/usr/bin/env python3
"""
build_web_preview.py — 把固件里的精灵/动画/字体导出成网页可直接用的 data.js

输出:
  web/data.js   window.DIGI_DATA = { sprites, chars, font }
  web/preview.html 由模板生成（见 build_html）

素材来源与固件完全一致:
  src/assets/sprites.h        程序化精灵（蛋/墓碑/究极体兜底）
  src/assets/anim_data.h      GIF 动画帧
  Adafruit GFX glcdfont.c     5x7 字库（和真机同一套）
"""
from __future__ import annotations

import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
WEB = os.path.join(ROOT, "web")

SPRITES_H = os.path.join(ROOT, "src", "assets", "sprites.h")
ANIM_H = os.path.join(ROOT, "src", "assets", "anim_data.h")
GLCDFONT = os.path.join(ROOT, ".pio", "libdeps", "esp32dev",
                        "Adafruit GFX Library", "glcdfont.c")


def read(p):
    with open(p, encoding="utf-8", errors="replace") as f:
        return f.read()


def parse_rows(txt, name):
    m = re.search(r"SPR_%s\[\] = \{(.*?)\};" % re.escape(name), txt, re.S)
    if not m:
        return None
    return re.findall(r'"([0-9A-F]+)"', m.group(1))


def parse_pal(txt, name):
    m = re.search(r"\b%s\[16\] = \{([^}]*)\}" % re.escape(name), txt)
    if not m:
        return None
    return [int(v.strip(), 16) & 0xFFFF
            for v in m.group(1).split(",") if v.strip()]


def build():
    sp = read(SPRITES_H)
    an = read(ANIM_H)

    # ---- 程序化精灵（SRPITES[] 表 + 各行 + 调色板）----
    table = re.search(r"static const SpriteDef SPRITES\[\] = \{(.*?)\n\};", sp, re.S).group(1)
    statics = []
    for w, h, spr, pal in re.findall(r"\{\s*(\d+),\s*(\d+),\s*(SPR_\w+),\s*(PAL_\w+)\s*\}", table):
        statics.append({
            "name": spr[4:],
            "w": int(w), "h": int(h),
            "rows": parse_rows(sp, spr[4:]),
            "pal": parse_pal(sp, pal),
        })

    # ---- 动画角色 ----
    chars = {}
    entry_re = re.compile(
        r"static const CharAnimEntry CHAR_ANIMS\[\] = \{(.*?)\n\};", re.S)
    entries = re.findall(r"\{\s*CH_(\w+),\s*\{([^}]*)\}\s*\}", entry_re.search(an).group(1))
    for char, clips in entries:
        pal = parse_pal(an, f"APAL_{char}")
        anims = {}
        for clip in re.findall(r"&(\w+_\w+)", clips):
            # clip 形如 KOROMON_IDLE
            m = re.search(r"%s = \{\s*(\d+)," % re.escape(clip), an)
            n = int(m.group(1))
            dm = re.search(r"\b%s_D\[\] = \{([^}]*)\}" % re.escape(clip), an)
            durs = [int(v) for v in dm.group(1).split(",") if v.strip()]
            frames = []
            for i in range(n):
                rows = parse_rows(an, f"{clip}_{i}")
                if rows is None:
                    raise RuntimeError(f"缺帧 {clip}_{i}")
                frames.append(rows)
            anims[clip[len(char) + 1:].lower()] = {"dur": durs, "frames": frames}
        chars[char.lower()] = {"pal": pal, "anims": anims}

    # ---- 5x7 字库 ----
    font = []
    if os.path.exists(GLCDFONT):
        g = read(GLCDFONT)
        body = g.split("{", 1)[1].split("};", 1)[0]
        vals = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{2})", body)]
        start = 32 * 5
        font = vals[start:start + 95 * 5]
        print(f"font: {len(font)//5} glyphs from glcdfont.c")
    else:
        print("[warn] 找不到 glcdfont.c，网页文字将用浏览器字体近似")

    data = {"statics": statics, "chars": chars, "font": font}
    os.makedirs(WEB, exist_ok=True)
    out = os.path.join(WEB, "data.js")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// AUTO-GENERATED by tools/build_web_preview.py\n")
        f.write("window.DIGI_DATA = ")
        json.dump(data, f, separators=(",", ":"))
        f.write(";\n")
    print(f"web/data.js {os.path.getsize(out)/1024:.0f} KB")
    print(f"  statics={len(statics)} chars={len(chars)} "
          f"frames={sum(len(a['frames']) for c in chars.values() for a in c['anims'].values())}")


if __name__ == "__main__":
    build()
