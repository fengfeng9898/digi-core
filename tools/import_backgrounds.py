#!/usr/bin/env python3
"""
import_backgrounds.py — 把白天/黑夜场景图压成 64x56 的索引色背景

输出:
  web/bg_data.js         window.DIGI_BG = { day:{pal,rows}, night:{pal,rows} }
  docs/bg_preview.png    放大预览（用于肉眼检查压缩质量）

处理:
  1. cover 裁剪到 64:56（保高度，宽度居中裁）
  2. LANCZOS 缩到 64x56
  3. 中位切分量化到 24 色（LED 上更接近像素画，也省空间）
"""
from __future__ import annotations

import os

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "bg")
WEB = os.path.join(ROOT, "web")
DOCS = os.path.join(ROOT, "docs")

W, H = 64, 56
COLORS = 24
B36 = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"


def rgb565(c):
    r, g, b = c
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def process(path):
    im = Image.open(path).convert("RGB")
    sw, sh = im.size
    # cover：按高度缩放，宽度居中裁
    scale = H / sh
    nw = int(round(sw * scale))
    im = im.resize((nw, H), Image.LANCZOS)
    left = max(0, (nw - W) // 2)
    im = im.crop((left, 0, left + W, H))

    q = im.quantize(colors=COLORS, method=Image.MEDIANCUT, dither=Image.NONE)
    pal = q.getpalette()[: COLORS * 3]
    palette = [tuple(pal[i * 3:i * 3 + 3]) for i in range(COLORS)]
    px = q.load()

    rows = []
    for y in range(H):
        rows.append("".join(B36[px[x, y]] for x in range(W)))
    return palette, rows, im


def main():
    scenes = {}
    previews = []
    for name, fn in (("day", "day_src.png"), ("night", "night_src.png")):
        path = os.path.join(SRC, fn)
        palette, rows, shrunk = process(path)
        scenes[name] = (palette, rows)
        previews.append((name, shrunk))
        print(f"{name}: {len(palette)} colors, {W}x{H}")

    os.makedirs(WEB, exist_ok=True)
    out = os.path.join(WEB, "bg_data.js")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// AUTO-GENERATED by tools/import_backgrounds.py\n")
        f.write("window.DIGI_BG = {\n")
        for name, (palette, rows) in scenes.items():
            pal = ",".join(f"0x{rgb565(c):04X}" for c in palette)
            f.write(f"  {name}: {{\n    w: {W}, h: {H},\n    pal: [{pal}],\n    rows: [\n")
            for r in rows:
                f.write(f'      "{r}",\n')
            f.write("    ]\n  },\n")
        f.write("};\n")
    print("wrote", out, f"{os.path.getsize(out)/1024:.0f} KB")

    # 预览：原图缩小 + 量化结果并排
    S = 8
    canvas = Image.new("RGB", ((W * S + 12) * 2, H * S + 24), (10, 12, 16))
    from PIL import ImageDraw
    dr = ImageDraw.Draw(canvas)
    for i, (name, shrunk) in enumerate(previews):
        palette, rows = scenes[name]
        rebuilt = Image.new("RGB", (W, H))
        rp = rebuilt.load()
        for y in range(H):
            for x in range(W):
                rp[x, y] = palette[B36.index(rows[y][x])]
        canvas.paste(rebuilt.resize((W * S, H * S), Image.NEAREST), (i * (W * S + 12), 0))
        dr.text((i * (W * S + 12) + 4, H * S + 4), name, fill=(150, 165, 180))
    canvas.save(os.path.join(DOCS, "bg_preview.png"))
    print("wrote docs/bg_preview.png")


if __name__ == "__main__":
    main()
